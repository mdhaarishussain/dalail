"""Import the Gemini research set (research/munazara) for DEV builds only (ADR 0008).

Writes corpus/research-import/ (regenerated every run): claim-only nodes clustered across videos,
counter-question nodes, edges and a report. Everything is origin: gemini-research, status: draft.
Gemini's claim IDs drifted between registries, so identity comes from content (e5 embeddings +
same topic/opponent); registry titles are suggestions only.
"""

from __future__ import annotations

import datetime as dt
import hashlib
import importlib.util
import itertools
import json
import sys
from collections import Counter, defaultdict
from collections.abc import Callable, Sequence
from dataclasses import dataclass, field
from importlib import resources
from pathlib import Path
from typing import Any

import yaml

from .errors import PipelineError

ORIGIN = "gemini-research"
GENERATED = "# GENERATED by `python -m dalail_pipeline import-research` — do not edit; re-run instead.\n"
Embed = Callable[[Sequence[str]], list[list[float]]]


def load_map() -> dict[str, Any]:
    return json.loads(resources.files("dalail_pipeline").joinpath("data/research_map.json").read_text())


def seconds(ts: str) -> int:
    first = str(ts).split("-")[0].strip()
    parts = [int(p) for p in first.split(":")]
    while len(parts) < 3:
        parts.insert(0, 0)
    return parts[0] * 3600 + parts[1] * 60 + parts[2]


def clock(s: int) -> str:
    return f"{s // 3600}:{s % 3600 // 60:02d}:{s % 60:02d}" if s >= 3600 else f"{s // 60:02d}:{s % 60:02d}"


def deep_link(url: str, s: int) -> str:
    return f"{url}{'&' if '?' in url else '?'}t={s}s"


def ws(s: str) -> str:
    return " ".join(str(s).split())


@dataclass
class Move:
    source_id: str
    raw: dict[str, Any]
    url: str
    start: int
    order: int

    @property
    def id(self) -> str:
        return str(self.raw.get("move_id"))

    @property
    def kind(self) -> str:
        return str(self.raw.get("kind"))

    @property
    def key(self) -> tuple[str, str]:
        return (self.source_id, self.id)

    @property
    def registry_id(self) -> str:
        return str(self.raw.get("maps_to") or self.raw.get("similar_to") or "")


@dataclass
class Video:
    source_id: str
    url: str
    title: str
    topics: list[str]
    speakers: dict[str, str]
    coverage: float
    moves: list[Move]
    phrasings: list[dict[str, Any]]

    def move(self, move_id: Any) -> Move | None:
        return next((m for m in self.moves if m.id == str(move_id)), None)


@dataclass
class Report:
    merges: list[dict[str, Any]] = field(default_factory=list)
    borderline: list[dict[str, Any]] = field(default_factory=list)
    skipped: list[tuple[str, str]] = field(default_factory=list)  # (where, reason)
    unresolved: list[tuple[str, str]] = field(default_factory=list)
    fallbacks: list[tuple[str, str]] = field(default_factory=list)


def _coverage_module(munazara: Path) -> Any:
    path = munazara / "tools" / "coverage.py"
    spec = importlib.util.spec_from_file_location("munazara_coverage", path)
    if spec is None or spec.loader is None:
        raise PipelineError(f"cannot load {path}")
    mod = importlib.util.module_from_spec(spec)
    sys.modules["munazara_coverage"] = mod
    spec.loader.exec_module(mod)
    return mod


def load_videos(munazara: Path) -> list[Video]:
    cov = _coverage_module(munazara)
    videos = []
    for f in sorted((munazara / "extractions").glob("*.yaml")):
        ex = yaml.safe_load(f.read_text(encoding="utf-8")) or {}
        sid = str(ex.get("source_id") or f.stem)
        tpath = munazara / "transcripts" / f"{sid}.md"
        fm: dict[str, Any] = {}
        coverage = 0.0
        if tpath.is_file():
            text = tpath.read_text(encoding="utf-8")
            fm = yaml.safe_load(text[4 : text.find("\n---", 4)]) or {}
            coverage = float(cov.analyse(tpath).coverage)
        url = str(fm.get("url") or f"https://www.youtube.com/watch?v={sid.removeprefix('yt-')}")
        speakers = {str(s.get("label")): str(s.get("name") or "") for s in fm.get("speakers") or []}
        moves = [Move(sid, m, url, seconds(m.get("timestamp") or "0"), i) for i, m in enumerate(ex.get("moves") or [])]
        videos.append(
            Video(sid, url, str(fm.get("title") or ""), [str(t) for t in fm.get("topics") or []], speakers,
                  coverage, moves, list(ex.get("phrasings") or []))
        )  # fmt: skip
    return videos


def speaker_name(video: Video, move: Move) -> str:
    label = str(move.raw.get("speaker") or "").split(" (")[0]
    return video.speakers.get(label, label)


def cosine(a: Sequence[float], b: Sequence[float]) -> float:
    return sum(x * y for x, y in zip(a, b, strict=True))


class UnionFind:
    def __init__(self, n: int) -> None:
        self.p = list(range(n))

    def find(self, i: int) -> int:
        while self.p[i] != i:
            self.p[i] = self.p[self.p[i]]
            i = self.p[i]
        return i

    def union(self, a: int, b: int) -> None:
        ra, rb = self.find(a), self.find(b)
        if ra != rb:
            self.p[max(ra, rb)] = min(ra, rb)


def import_research(munazara: Path, out_dir: Path, embed: Embed, topic_ids: set[str], opponent_ids: set[str],
                    today: dt.date | None = None) -> dict[str, Any]:  # fmt: skip
    cfg = load_map()
    rep = Report()
    videos = load_videos(munazara)
    if not videos:
        raise PipelineError(f"no extractions found in {munazara / 'extractions'}")
    registry = (yaml.safe_load((munazara / "registry/claims.yaml").read_text()) or {}).get("claims") or {}
    cq_catalogue = (yaml.safe_load((munazara / "registry/counter-questions.yaml").read_text()) or {}).get(
        "counter_questions"
    ) or {}
    skip_conf = set(cfg["skip_confidence"])

    # --- 1. opponent claims ----------------------------------------------------------
    claims: list[Move] = []
    claim_meta: dict[tuple[str, str], dict[str, str]] = {}
    for v in videos:
        for m in v.moves:
            if m.kind != "claim":
                continue
            where = f"{v.source_id} {m.id}"
            side = str(m.raw.get("side"))
            if str(m.raw.get("confidence")) in skip_conf:
                rep.skipped.append((where, "confidence: low"))
                continue
            relayed = side in cfg["relaying_sides"] and m.raw.get("reported")
            if side not in cfg["side_opponent"] and not relayed:
                rep.skipped.append((where, f"claim by side '{side}' (not an opponent claim)"))
                continue
            rid = m.registry_id
            parts = rid.split("-")
            topic = cfg["registry_prefix_topic"].get(parts[0]) if rid else None
            if topic is None:
                topic = next((cfg["video_topic"][t] for t in v.topics if t in cfg["video_topic"]), None)
                rep.fallbacks.append((where, f"topic from video topics -> {topic}"))
            if topic is None or topic not in topic_ids:
                rep.skipped.append((where, f"no known topic (registry id '{rid}', video topics {v.topics})"))
                continue
            opp = cfg["side_opponent"].get(side)
            if opp is None and len(parts) > 1:
                opp = cfg["registry_code_opponent"].get(parts[1])
            if opp is None:
                opp = "ali-mirza" if any(x.raw.get("side") == "ali-mirza" for x in v.moves) else "other"
                rep.fallbacks.append((where, f"opponent inferred -> {opp}"))
            if opp not in opponent_ids:
                rep.skipped.append((where, f"opponent '{opp}' not in opponents.yaml"))
                continue
            claims.append(m)
            claim_meta[m.key] = {"topic": topic, "opponent": opp}

    # --- 2. cluster across videos ----------------------------------------------------------
    cl = cfg["cluster"]
    vs = embed([ws(m.raw.get("summary_en") or m.raw.get("quote") or "") for m in claims])
    vq = embed([ws(m.raw.get("quote") or "") for m in claims])
    uf = UnionFind(len(claims))
    for i in range(len(claims)):
        for j in range(i + 1, len(claims)):
            a, b = claims[i], claims[j]
            if a.source_id == b.source_id or claim_meta[a.key] != claim_meta[b.key]:
                continue
            s, q = cosine(vs[i], vs[j]), cosine(vq[i], vq[j])
            pair = {"a": f"{a.source_id} {a.id}", "b": f"{b.source_id} {b.id}", "summary_cos": round(s, 3),
                    "quote_cos": round(q, 3), "a_text": ws(a.raw.get("summary_en")),
                    "b_text": ws(b.raw.get("summary_en"))}  # fmt: skip
            if s >= cl["merge_summary"] or (s >= cl["merge_both"] and q >= cl["merge_both"]):
                uf.union(i, j)
                rep.merges.append(pair)
            elif s >= cl["borderline_summary"] or q >= cl["borderline_quote"]:
                rep.borderline.append(pair)

    groups: dict[int, list[int]] = defaultdict(list)
    for i in range(len(claims)):
        groups[uf.find(i)].append(i)
    vid_index = {v.source_id: n for n, v in enumerate(videos)}
    ordered = sorted(
        groups.values(),
        key=lambda g: (
            claim_meta[claims[g[0]].key]["topic"],
            min((vid_index[claims[i].source_id], claims[i].start) for i in g),
        ),
    )  # fmt: skip
    node_of: dict[tuple[str, str], str] = {}
    nodes: list[dict[str, Any]] = []
    per_topic: Counter[str] = Counter()
    video_by_id = {v.source_id: v for v in videos}
    for g in ordered:
        members = sorted((claims[i] for i in g), key=lambda m: (vid_index[m.source_id], m.start))
        rep_move = next((m for m in members if m.raw.get("confidence") == "high"), members[0])
        meta = claim_meta[rep_move.key]
        per_topic[meta["topic"]] += 1
        nid = f"rs-{meta['topic']}-{per_topic[meta['topic']]:03d}"
        for m in members:
            node_of[m.key] = nid
        suggested = next((registry[m.registry_id]["title"] for m in members if m.registry_id in registry), None)
        nodes.append({
            "id": nid, "node_type": "claim-only", "origin": ORIGIN, "status": "draft",
            "topic": meta["topic"], "opponent": [meta["opponent"]],
            "claim": ws(rep_move.raw.get("quote")), "summary_en": ws(rep_move.raw.get("summary_en")),
            "move_type": str(rep_move.raw.get("move_type") or ""), "suggested_name": suggested,
            "registry_ids_seen": sorted({m.registry_id for m in members if m.registry_id}),
            "occurrences": [{
                "source_id": m.source_id, "move_id": m.id, "title": video_by_id[m.source_id].title,
                "url": m.url, "start_s": m.start, "at": clock(m.start), "deep_link": deep_link(m.url, m.start),
                "quote": ws(m.raw.get("quote")), "summary_en": ws(m.raw.get("summary_en")),
                "move_type": str(m.raw.get("move_type") or ""), "confidence": str(m.raw.get("confidence")),
                "coverage": round(video_by_id[m.source_id].coverage, 2),
            } for m in members],
            "aliases": [], "candidate_responses": [],
        })  # fmt: skip
    node_by_id = {n["id"]: n for n in nodes}

    def claim_for(video: Video, move: Move) -> Move | None:
        """Follow responds_to (and same-file `answers`) back to a selected claim move."""
        seen: set[str] = set()
        cur: Move | None = move
        while cur is not None and cur.id not in seen:
            seen.add(cur.id)
            target_id = cur.raw.get("responds_to")
            if not target_id:
                ans = cur.raw.get("answers")
                hits = [c for c in video.moves if ans and c.kind == "claim" and c.registry_id == ans]
                return hits[0] if hits and hits[0].key in node_of else None
            target = video.move(target_id)
            if target is None:
                return None
            if target.kind == "claim" and target.key in node_of:
                return target
            cur = target
        return None

    # --- 3. aliases: claim quotes + phrasings -------------------------------------------------
    for n in nodes:
        n["aliases"] = list(dict.fromkeys(o["quote"] for o in n["occurrences"] if o["quote"]))
    for v in videos:
        for i, p in enumerate(v.phrasings):
            text = ws(p.get("text") or "")
            if not text:
                continue
            target = None
            cands = [m for m in v.moves if m.kind == "claim" and m.key in node_of]
            same = [m for m in cands if p.get("maps_to") and m.registry_id == p.get("maps_to")]
            pool = same or [m for m in cands if abs(m.start - seconds(p.get("timestamp") or "0")) <= 120]
            if pool:
                ts = seconds(p.get("timestamp") or "0")
                target = min(pool, key=lambda m: abs(m.start - ts))
            if target is None:
                rep.unresolved.append((f"{v.source_id} phrasing {i + 1}", f"no claim for maps_to {p.get('maps_to')}"))
                continue
            aliases = node_by_id[node_of[target.key]]["aliases"]
            if text not in aliases:
                aliases.append(text)

    # --- 4. candidate responses (Mufti Rashid) + counter-questions --------------------------------
    cqs: list[dict[str, Any]] = []
    edges: set[tuple[str, str, str]] = set()
    for v in videos:
        for m in v.moves:
            where = f"{v.source_id} {m.id}"
            if m.kind not in ("response", "counter-question"):
                continue
            if str(m.raw.get("confidence")) in skip_conf:
                rep.skipped.append((where, "confidence: low"))
                continue
            claim = claim_for(v, m)
            if m.kind == "response":
                if cfg["rashid_name_contains"] not in speaker_name(v, m):
                    rep.skipped.append(
                        (where, f"response by {speaker_name(v, m) or m.raw.get('speaker')} (not Mufti Rashid)")
                    )
                    continue
                if claim is None:
                    rep.unresolved.append((where, "response not linked to an imported claim"))
                    continue
                node_by_id[node_of[claim.key]]["candidate_responses"].append({
                    "source_id": v.source_id, "move_id": m.id, "speaker": speaker_name(v, m),
                    "quote": ws(m.raw.get("quote")), "summary_en": ws(m.raw.get("summary_en")),
                    "move_type": str(m.raw.get("move_type") or ""),
                    "evidence_as_said": [
                        ws(e.get("as_said")) for e in m.raw.get("evidence_cited") or [] if e.get("as_said")
                    ],
                    "start_s": m.start, "at": clock(m.start), "deep_link": deep_link(m.url, m.start),
                    "confidence": str(m.raw.get("confidence")),
                })  # fmt: skip
            else:
                cq_id = f"rs-cq-{len(cqs) + 1:03d}"
                mapped = str(m.raw.get("maps_to") or "")
                cqs.append({
                    "id": cq_id, "node_type": "counter-question", "origin": ORIGIN, "status": "draft",
                    "topic": node_by_id[node_of[claim.key]]["topic"] if claim else None,
                    "counters": [node_of[claim.key]] if claim else [],
                    "quote": ws(m.raw.get("quote")), "summary_en": ws(m.raw.get("summary_en")),
                    "move_type": str(m.raw.get("move_type") or ""), "speaker": speaker_name(v, m),
                    "suggested_name": (cq_catalogue.get(mapped) or {}).get("title"),
                    "source_id": v.source_id, "move_id": m.id, "start_s": m.start, "at": clock(m.start),
                    "deep_link": deep_link(m.url, m.start), "confidence": str(m.raw.get("confidence")),
                })  # fmt: skip
                if claim:
                    edges.add((cq_id, node_of[claim.key], "counters"))
                else:
                    rep.unresolved.append((where, "counter-question not linked to an imported claim"))

    # --- 5. follow-ups from the order of claims within each video ------------------------------
    for v in videos:
        seq = sorted((m for m in v.moves if m.kind == "claim" and m.key in node_of), key=lambda m: (m.start, m.order))
        for a, b in itertools.pairwise(seq):
            replied = any(claim_for(v, r) is a and a.start <= r.start <= b.start for r in v.moves if r.kind != "claim")
            na, nb = node_of[a.key], node_of[b.key]
            if replied and na != nb:
                edges.add((na, nb, "follow_up"))

    for n in nodes:
        n["candidate_responses"].sort(key=lambda r: (vid_index[r["source_id"]], r["start_s"]))
    cq_topics = {c["id"]: c["topic"] for c in cqs}
    edge_list = [{"from": a, "to": b, "kind": k} for a, b, k in sorted(edges)]

    # --- write ----------------------------------------------------------------------------------
    out_dir.mkdir(parents=True, exist_ok=True)
    for old in out_dir.glob("*"):
        if old.is_file():
            old.unlink()
    dump = lambda obj: GENERATED + yaml.safe_dump(obj, sort_keys=False, allow_unicode=True, width=1000)  # noqa: E731
    (out_dir / "nodes.yaml").write_text(dump(nodes), encoding="utf-8")
    (out_dir / "counter_questions.yaml").write_text(dump(cqs), encoding="utf-8")
    (out_dir / "edges.yaml").write_text(dump(edge_list), encoding="utf-8")
    inputs = sorted(
        p for d in ("extractions", "transcripts", "registry") for p in (munazara / d).rglob("*") if p.is_file()
    )
    manifest = {
        "origin": ORIGIN,
        "generated_on": (today or dt.date.today()).isoformat(),
        "thresholds": cl,
        "counts": {"videos": len(videos), "claim_moves": len(claims), "claim_nodes": len(nodes),
                   "counter_questions": len(cqs), "edges": Counter(e["kind"] for e in edge_list),
                   "aliases": sum(len(n["aliases"]) for n in nodes),
                   "candidate_responses": sum(len(n["candidate_responses"]) for n in nodes)},
        "inputs_sha256": hashlib.sha256(b"".join(p.read_bytes() for p in inputs)).hexdigest(),
    }  # fmt: skip
    (out_dir / "manifest.json").write_text(json.dumps(manifest, indent=2, default=dict) + "\n")
    (out_dir / "report.md").write_text(_report_md(nodes, cqs, cq_topics, edge_list, rep, manifest), encoding="utf-8")
    return manifest


def _report_md(nodes: list[dict[str, Any]], cqs: list[dict[str, Any]], cq_topics: dict[str, Any],
               edges: list[dict[str, str]], rep: Report, manifest: dict[str, Any]) -> str:  # fmt: skip
    c = manifest["counts"]
    out = [
        "<!-- GENERATED by `python -m dalail_pipeline import-research` — do not edit -->",
        "# Research import report (dev builds only — ADR 0008)",
        "",
        f"Generated {manifest['generated_on']}. Origin `{ORIGIN}`, status `draft`. Never shipped in prod builds.",
        "",
        f"- Videos: {c['videos']}; opponent claim moves imported: {c['claim_moves']} → "
        f"**{c['claim_nodes']} claim nodes** "
        f"after clustering ({len(rep.merges)} merged pairs)",
        f"- Aliases: {c['aliases']}; candidate responses (Mufti Rashid): {c['candidate_responses']}; "
        f"counter-questions: {c['counter_questions']}",
        f"- Edges: {dict(c['edges'])}",
        f"- Thresholds: `{json.dumps(manifest['thresholds'])}`",
        "",
        "## Claims per topic",
        "",
        "| Topic | Claim nodes | Aliases | Candidate responses | Counter-questions |",
        "| --- | --- | --- | --- | --- |",
    ]
    by_topic: dict[str, list[dict[str, Any]]] = defaultdict(list)
    for n in nodes:
        by_topic[n["topic"]].append(n)
    cq_count = Counter(t for t in cq_topics.values() if t)
    for t, ns in sorted(by_topic.items()):
        out.append(f"| {t} | {len(ns)} | {sum(len(n['aliases']) for n in ns)} | "
                   f"{sum(len(n['candidate_responses']) for n in ns)} | {cq_count.get(t, 0)} |")  # fmt: skip
    out += ["", f"## Merges ({len(rep.merges)}) — claims judged to be the same across videos", ""]
    out += [f"- `{m['a']}` + `{m['b']}` (summary {m['summary_cos']}, quote {m['quote_cos']}): "
            f"{m['a_text']} ‖ {m['b_text']}" for m in rep.merges] or ["- none"]  # fmt: skip
    out += ["", f"## Borderline pairs for review ({len(rep.borderline)}) — not merged", ""]
    out += [f"- `{m['a']}` vs `{m['b']}` (summary {m['summary_cos']}, quote {m['quote_cos']}): "
            f"{m['a_text']} ‖ {m['b_text']}" for m in rep.borderline] or ["- none"]  # fmt: skip
    out += ["", f"## Skipped moves ({len(rep.skipped)})", ""]
    reasons = Counter(r for _, r in rep.skipped)
    out += [f"- {n}x {r}" for r, n in reasons.most_common()] or ["- none"]
    out += ["", "<details><summary>All skipped moves</summary>", ""]
    out += [f"- `{w}` — {r}" for w, r in rep.skipped] + ["", "</details>"]
    out += ["", f"## Unresolved references ({len(rep.unresolved)})", ""]
    out += [f"- `{w}` — {r}" for w, r in rep.unresolved] or ["- none"]
    out += ["", f"## Fallbacks used ({len(rep.fallbacks)})", ""]
    out += [f"- `{w}` — {r}" for w, r in rep.fallbacks] or ["- none"]
    out += ["", "## Not imported", "",
            "- The 'Common Debate Sequences' prose in `notes/` (garbled symbols, drifted IDs). Follow-ups come from "
            "the order of claims within each video instead (claim A → next claim B, once A was answered)."]  # fmt: skip
    return "\n".join(out) + "\n"
